const FIX = resolve(__dirname, '../fixtures/repos')
const TMP = resolve(__dirname, '../.tmp/cli-test')

async function cli(...argv: string[]): Promise<{ code: number; out: string; err: string }> {
  let out = ''
  let err = ''
  const code = await run(argv, { out: (s) => (out += s + '\n'), err: (s) => (err += s + '\n') })
  return { code, out, err }
}

async function freshRepo(name: string): Promise<string> {
  const dir = join(TMP, name)
  await rm(dir, { recursive: true, force: true })
  await mkdir(TMP, { recursive: true })
  await cp(join(FIX, name), dir, { recursive: true })
  return dir
}

describe('argument parsing', () => {
  it('reads commands, options and --flag=value', () => {
    const o = parseArgs(['check', 'repo', '--map=docs/a.crtgrphr', '--strict', '-q', '--theme', 'dark'])
    expect(o).toMatchObject({ cmd: 'check', positional: ['repo'], map: 'docs/a.crtgrphr', strict: true, quiet: true, theme: 'dark' })
  })

  it('rejects unknown options and missing values with exit code 2', async () => {
    expect((await cli('scan', '--nope')).code).toBe(2)
    expect((await cli('scan', '--out')).err).toContain('--out needs a value')
    expect((await cli('check')).err).toContain('check needs --map')
    expect((await cli('frobnicate')).code).toBe(2)
  })

  it('prints help and version', async () => {
    expect((await cli('--help')).out).toContain('crtgrphr check [dir] --map <file>')
    expect((await cli('--version')).code).toBe(0)
  })
})

describe('scan, check and update', () => {
  it('scan writes a map with a relative origin, and all exports', async () => {
    const dir = await freshRepo('compose-basic')
    const map = join(dir, 'docs/architecture.crtgrphr')
    const r = await cli('scan', dir, '--out', map, '--mermaid', join(dir, 'docs/architecture.md'), '--svg', join(dir, 'docs/a.svg'), '--drawio', join(dir, 'docs/a.drawio'), '--c4', join(dir, 'docs/a.puml'))
    expect(r.code).toBe(0)
    const text = await readFile(map, 'utf8')
    expect(text).toContain('"origin": {"kind":"repo","root":".."')
    expect(parseProject(text).value.diagram.nodes).toHaveLength(7)
    expect(await readFile(join(dir, 'docs/architecture.md'), 'utf8')).toMatch(/^<!-- Generated by Cartographer[\s\S]*```mermaid\nflowchart LR/)
    expect(await readFile(join(dir, 'docs/a.svg'), 'utf8')).toMatch(/^<svg/)
    expect(existsSync(join(dir, 'docs/a.drawio'))).toBe(true)
    expect(existsSync(join(dir, 'docs/a.puml'))).toBe(true)
  })

  it('a re-scan of unchanged code leaves the map file byte-for-byte the same', async () => {
    const dir = await freshRepo('compose-basic')
    const map = join(dir, 'architecture.crtgrphr')
    await cli('scan', dir, '--out', map)
    const before = await readFile(map, 'utf8')
    await cli('scan', dir, '--out', map)
    expect(await readFile(map, 'utf8')).toBe(before)
  })

  it('check passes, then fails with a report when the code changes, and --update fixes it', async () => {
    const dir = await freshRepo('compose-basic')
    const map = join(dir, 'docs/architecture.crtgrphr')
    await cli('scan', dir, '--out', map)
    // origin.root in the file is used when no folder is given
    expect((await cli('check', '--map', map)).code).toBe(0)

    await appendFile(join(dir, 'docker-compose.yml'), '  search:\n    image: opensearchproject/opensearch:2\n    depends_on: [db]\n')
    const report = join(dir, 'drift.md')
    const drift = await cli('check', '--map', map, '--report', report)
    expect(drift.code).toBe(1)
    const md = await readFile(report, 'utf8')
    expect(md).toContain('## Architecture map drift: 2 added')
    expect(md).toContain('+ search (opensearchproject/opensearch)')
    expect(md).toContain('+ search → db')

    expect((await cli('check', '--map', map, '--update', '-q')).code).toBe(0)
    expect((await cli('check', '--map', map)).code).toBe(0)
    expect(parseProject(await readFile(map, 'utf8')).value.diagram.nodes.some((n) => n.id === 'search')).toBe(true)
  })

  it('keeps hand edits through an update', async () => {
    const dir = await freshRepo('compose-basic')
    const map = join(dir, 'm.crtgrphr')
    await cli('scan', dir, '--out', map)
    const text = (await readFile(map, 'utf8')).replace('{"id":"api","label":"api"', '{"id":"api","label":"Orders API"').replace('"source":"docker-compose.yml#services.api"', '"edited":"label","source":"docker-compose.yml#services.api"')
    await (await import('node:fs/promises')).writeFile(map, text)
    await appendFile(join(dir, 'docker-compose.yml'), '  search:\n    image: opensearch\n')
    await cli('scan', dir, '--out', map)
    const after = parseProject(await readFile(map, 'utf8')).value.diagram
    expect(after.nodes.find((n) => n.id === 'api')?.label).toBe('Orders API')
    expect(after.nodes.some((n) => n.id === 'search')).toBe(true)
  })

  it('by default only structure is drift; --strict also counts details', async () => {
    const dir = await freshRepo('compose-basic')
    const map = join(dir, 'm.crtgrphr')
    await cli('scan', dir, '--out', map)
    // change only an edge label (links → depends on) and an image tag: details, not structure
    const compose = join(dir, 'docker-compose.yml')
    const yml = (await readFile(compose, 'utf8')).replace('image: nginx:1.27', 'image: nginx:1.28')
    await (await import('node:fs/promises')).writeFile(compose, yml.replace('image: postgres:16', 'image: postgis/postgis:16'))
    const relaxed = await cli('check', '--map', map)
    expect(relaxed.code).toBe(0)
    expect(relaxed.out).toContain('only details changed')
    expect((await cli('check', '--map', map, '--strict')).code).toBe(1)
  })

  it('export writes formats from a saved map, and errors helpfully', async () => {
    const dir = await freshRepo('compose-basic')
    const map = join(dir, 'm.crtgrphr')
    await cli('scan', dir, '--out', map)
    expect((await cli('export', map, '--c4', join(dir, 'm.puml'))).code).toBe(0)
    expect((await cli('export', map)).err).toContain('at least one of')
    expect((await cli('check', '--map', join(dir, 'missing.crtgrphr'))).err).toContain('create one with')
  })
})

describe('structuralDiff', () => {
  it('drops sublabel and edge-label changes but keeps renames and role changes', () => {
    const a: IRDiagram = { id: 'a', title: 'a', type: 'architecture', nodes: [{ id: 'x', label: 'x', sublabel: '3 files', role: 'backend', meta: { source: 's' } }], edges: [] }
    const b: IRDiagram = { ...a, nodes: [{ id: 'x', label: 'x', sublabel: '4 files', role: 'backend' }] }
    expect(structuralDiff(diffDiagrams(a, b)).changedNodes).toHaveLength(0)
    const c: IRDiagram = { ...a, nodes: [{ id: 'x', label: 'x', role: 'database' }] }
    expect(structuralDiff(diffDiagrams(a, c)).changedNodes).toHaveLength(1)
  })
})

describe('draw.io and C4 exports', () => {
  it('draw.io: every node, group frame and edge, with layout geometry and bends', async () => {
    const d = await scanRepository(join(FIX, 'k8s-basic'))
    const xml = diagramToDrawio(d, await layoutDiagram(d))
    expect(xml).toMatch(/^<\?xml[\s\S]*<mxfile host="Cartographer"/)
    for (const n of d.nodes) expect(xml).toContain(`id="n-${n.id}"`)
    for (const e of d.edges) expect(xml).toContain(`source="n-${e.source}" target="n-${e.target}"`)
    expect(xml).toContain('shape=cylinder3') // postgres
    expect(xml).toMatch(/<mxGeometry x="[\d.]+" y="[\d.]+" width="[\d.]+" height="[\d.]+" as="geometry"\/>/)
    expect(xml).not.toMatch(/value="[^"]*<b>/) // labels are escaped
  })

  it('draw.io: groups become frames', async () => {
    const d = await scanRepository(join(FIX, 'app-plus-terraform'))
    const xml = diagramToDrawio(d, await layoutDiagram(d))
    expect(xml).toContain('id="g-infrastructure" value="Infrastructure (Terraform)"')
  })

  it('C4-PlantUML: element kinds, boundaries, relations and safe aliases', async () => {
    const d = await scanRepository(join(FIX, 'app-plus-terraform'))
    const puml = diagramToC4PlantUml(d)
    expect(puml).toMatch(/^@startuml\n/)
    expect(puml).toContain('!include <C4/C4_Container>')
    expect(puml).toContain('System_Boundary(infrastructure, "Infrastructure (Terraform)") {')
    expect(puml).toContain('ContainerDb(main_rds, "shop-db", "RDS", "")')
    expect(puml).toContain('Container(app, "shop-api", "Express")')
    expect(puml).toContain('Rel(app, postgresql, "Uses")')
    expect(puml.trimEnd().endsWith('@enduml')).toBe(true)

    const k = diagramToC4PlantUml(await scanRepository(join(FIX, 'k8s-basic')))
    expect(k).toContain('System_Ext(ext_payments, "payments", "external · api.stripe.com")')
    expect(k).toContain('AddRelTag("async", $lineStyle = DashedLine())')
    expect(k).toContain('$tags="async"')
  })
})
