// Generates src/shared/brand-icons.ts from the simple-icons package (CC0-1.0):
// the logos drawn in a node's badge, for the brands the scanner and the AI use.
//   node scripts/brand-icons.mjs
// Brands simple-icons doesn't carry (AWS, Azure, SQL Server, OpenAI...) keep the
// lettered badge.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as si from 'simple-icons'

const WANT = [
  // data and messaging
  'postgresql', 'mysql', 'mariadb', 'mongodb', 'sqlite', 'redis', 'apachekafka', 'rabbitmq', 'elasticsearch',
  'opensearch', 'apachecassandra', 'clickhouse', 'neo4j', 'minio', 'influxdb', 'cockroachlabs', 'supabase',
  'firebase', 'snowflake', 'apachespark', 'apacheairflow', 'dbt', 'prisma',
  // edge, cloud and platforms
  'nginx', 'traefikproxy', 'cloudflare', 'googlecloud', 'kubernetes', 'helm', 'terraform', 'docker', 'vercel',
  'netlify', 'heroku', 'digitalocean', 'github', 'gitlab',
  // services
  'stripe', 'anthropic', 'auth0', 'twilio', 'slack', 'sentry', 'datadog', 'grafana', 'prometheus', 'graphql',
  'apollographql',
  // frameworks and runtimes
  'nodedotjs', 'python', 'go', 'rust', 'react', 'nextdotjs', 'vuedotjs', 'angular', 'svelte', 'express', 'nestjs',
  'fastapi', 'django', 'flask', 'springboot', 'dotnet', 'kotlin', 'electron',
]

const bySlug = new Map(Object.values(si).filter((x) => x && x.slug).map((x) => [x.slug, x]))
const found = WANT.filter((s) => bySlug.has(s))
const missing = WANT.filter((s) => !bySlug.has(s))
const pkg = JSON.parse(
  (await import('node:fs')).readFileSync(fileURLToPath(new URL('../node_modules/simple-icons/package.json', import.meta.url)), 'utf8'),
)

const lines = [
  '/**',
  ' * Brand logos for node badges: 24×24 SVG paths from Simple Icons',
  ` * (https://simpleicons.org, CC0-1.0), v${pkg.version}. Generated by scripts/brand-icons.mjs;`,
  ' * do not edit by hand. Logos are trademarks of their owners and only identify the',
  ' * technology a part uses.',
  ' */',
  'export interface BrandIcon {',
  '  title: string',
  '  path: string',
  '}',
  '',
  'export const BRAND_ICONS: Record<string, BrandIcon> = {',
  ...found.map((s) => `  ${JSON.stringify(s)}: { title: ${JSON.stringify(bySlug.get(s).title)}, path: ${JSON.stringify(bySlug.get(s).path)} },`),
  '}',
  '',
  'export function brandIcon(brand: string | undefined): BrandIcon | undefined {',
  '  return brand ? BRAND_ICONS[brand.toLowerCase()] : undefined',
  '}',
  '',
]
writeFileSync(fileURLToPath(new URL('../src/shared/brand-icons.ts', import.meta.url)), lines.join('\n'))
console.log(`src/shared/brand-icons.ts: ${found.length} icons${missing.length ? `; not in simple-icons: ${missing.join(', ')}` : ''}`)
